import assert from 'node:assert/strict';
import { boundedZoom, latestOnly, shareViewer } from '../src/lib/resume-controls.mjs';
assert.equal(boundedZoom(.01), .25);
assert.equal(boundedZoom(9), 3);
assert.equal(boundedZoom(1.25), 1.25);
const revisions = latestOnly();
const old = revisions.next();
const current = revisions.next();
assert.equal(revisions.current(old), false);
assert.equal(revisions.current(current), true);
let copied;
assert.equal(await shareViewer({ clipboard: { writeText: async url => { copied = url; } } }, 'https://example.test/resume/'), 'copied');
assert.equal(copied, 'https://example.test/resume/');
assert.equal(await shareViewer({ clipboard: { writeText: async () => { throw Error('denied'); } } }, 'url'), 'error');
assert.equal(await shareViewer({}, 'url'), 'error');
assert.equal(await shareViewer({ share: async () => {}, clipboard: { writeText: () => { throw Error('must not copy'); } } }, 'url'), 'shared');
assert.equal(await shareViewer({ share: async () => { throw { name: 'AbortError' }; } }, 'url'), 'cancelled');
assert.equal(await shareViewer({ share: async () => { throw Error('failed'); }, clipboard: { writeText: async () => {} } }, 'url'), 'copied');
console.log('test-resume-controls: ok');
